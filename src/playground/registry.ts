import type { Ground } from './kit'

/*
 * What the Playground lists, in order. Metadata only — the code for each
 * piece is loaded on demand from src/playground/<key>.ts (see loaders.ts),
 * so this file is safe to pre-render and cheap to ship.
 */

export type Kind = 'showcase' | 'motion' | 'game'

export interface Entry {
  /** module path under src/playground, e.g. 'games/debris' */
  key: string
  /** URL hash and React key, e.g. 'debris' */
  id: string
  kind: Kind
  /** catalogue number, e.g. 'M.03' */
  code: string
  title: string
  /** short theme line for the card */
  theme: string
  blurb: string
  ground: Ground
  /** games: the classic it follows */
  after?: string
  /** viewer footer hint */
  controls?: string
  /** seconds to fast-forward a preview card so it never opens on an empty frame */
  preroll?: number
}

